import pandas as pd

# load dataset
df=pd.read_csv("retail_sales_cleaned.csv")

# total revenue
total_revenue=df["Sales"].sum()

# total profit
total_profit=df["Profit"].sum()

# total orders
total_orders=df["Order_ID"].nunique()

# total customers
total_customers=df["Customer_ID"].nunique()

# average order value
aov=total_revenue / total_orders if total_orders > 0 else 0

# profit margin
profit_margin=(
      (total_profit / total_revenue) * 100
      if total_revenue != 0 else 0
)

# monthly revenue growth
df["Order_Date"]=pd.to_datetime(
      df["Order_Date"], errors="coerce", dayfirst=True
)

df["Month"]=df["Order_Date"].dt.to_period("M")
monthly_sales=df.groupby("Month")["Sales"].sum().sort_index()

growth = None

if len(monthly_sales) >= 2:
      previous=monthly_sales.iloc[-2]
      current=monthly_sales.iloc[-1]
      
      if previous != 0:
            growth = ((current - previous) / previous) * 100
            
# KPI's
print("\n---- Retail Sales KPI Report ----")
print(f"1. Total Revenue: {total_revenue:.2f}")
print(f"2. Total Profit: {total_profit:.2f}")
print(f"3. Total Orders: {total_orders}")
print(f"4. Total Customers: {total_customers}")
print(f"5. Average Order Value: {aov:.2f}")
print(f"6. Profit Margin: {profit_margin:.2f}%")

if growth is not None:
      print(f"7. Revenue Growth: {growth:.2f}%")
else:
      print("7. Revenue Growth: Not available")
      
